<?php
declare(strict_types=1);

require_once __DIR__ . '/../api/ProviderConfig.php';
require_once __DIR__ . '/../api/lib/KraDb.php';
require_once __DIR__ . '/../api/lib/KraRouterGateway.php';
require_once __DIR__ . '/../api/lib/KraAudit.php';
require_once __DIR__ . '/../api/lib/KraTaskEngine.php';
require_once __DIR__ . '/../api/lib/KraVaultSync.php';
require_once __DIR__ . '/../api/lib/KraAgentChat.php';

function check7(bool $condition, string $message): void
{
    if (!$condition) {
        fwrite(STDERR, "[FAIL] {$message}\n");
        exit(1);
    }
    echo "[PASS] {$message}\n";
}

$projectRoot = realpath(__DIR__ . '/..');
check7($projectRoot !== false, 'Project root resolves.');

$dimas = KraAgentChat::dispatch([
    'channel' => 'dimas',
    'message' => 'Audit Phase 7 workspace security',
]);
check7($dimas['ok'] === true, 'Dimas dispatch returns ok=true.');
check7(str_contains($dimas['message'], 'Laporan Audit Dimas'), 'Dimas returns live audit report.');
check7(str_contains($dimas['message'], 'APPROVED') || str_contains($dimas['message'], 'REJECTED'),
    'Dimas report includes audit verdict.');

$siti = KraAgentChat::dispatch([
    'channel' => 'siti',
    'message' => 'Status database dan runtime server',
]);
check7($siti['ok'] === true, 'Siti dispatch returns ok=true.');
check7(str_contains($siti['message'], 'Laporan Operasional Siti'), 'Siti returns live operations report.');
check7(str_contains($siti['message'], 'Database MySQL'), 'Siti report includes database status.');

$budi = KraAgentChat::dispatch([
    'channel' => 'budi',
    'message' => 'Buatkan fungsi validasi email dalam file validator.php',
]);
check7(is_array($budi['proposal']), 'Budi creates an approval-gated proposal.');
check7(str_starts_with((string) $budi['proposal']['targetFile'], 'proposals/'),
    'Proposal target remains inside proposals directory.');
check7(str_contains((string) $budi['proposal']['proposedContent'], 'Generated by')
    || str_contains((string) $budi['proposal']['proposedContent'], 'function')
    || str_contains((string) $budi['proposal']['proposedContent'], '<?php'),
    'Proposal contains generated or structured content.');

$maya = KraAgentChat::dispatch([
    'channel' => 'maya',
    'message' => 'Edit file tools/verify-phase7.php untuk menambahkan komentar dokumentasi',
]);
check7($maya['ok'] === true, 'Maya dispatch returns ok=true.');
check7(is_array($maya['proposal']), 'Maya creates an approval-gated modification proposal.');
check7(($maya['proposal']['targetFile'] ?? '') === 'tools/verify-phase7.php',
    'Maya preserves real relative target path from read-only context.');
check7(!empty($maya['proposal']['proposedContent']), 'Maya produces proposed replacement content.');

$vaultDir = KraVaultSync::getVaultDir();
$dashboard = $vaultDir !== '' ? $vaultDir . DIRECTORY_SEPARATOR . 'Dashboard KRA Project.md' : '';
check7($dashboard !== '' && is_file($dashboard), 'Obsidian dashboard is available for memory ingestion.');

$scan = KraAudit::run((string) $projectRoot);
check7(($scan['summary']['files'] ?? 0) > 0, 'Audit scanner reports project files.');

$dashboardResponse = [
    'connected' => is_file($dashboard),
    'milestones' => is_file($dashboard)
        ? (int) preg_match_all('/^\d+\.\s+\*\*/m', (string) file_get_contents($dashboard)) : 0,
];
check7($dashboardResponse['connected'], 'Vault dashboard connection is true.');
check7($dashboardResponse['milestones'] > 0, 'Vault dashboard contains indexed milestones.');

echo "PHASE 7 VERIFICATION PASSED\n";
